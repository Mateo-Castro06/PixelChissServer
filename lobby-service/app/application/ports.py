class Actor(Protocol):
    id: str
    token: str


class PlayerNames(Protocol):
    async def get_display_name(self, user: Actor) -> str: ...


class GameCreation(Protocol):
    async def create_game(self, plan: GameInitialization) -> None: ...


class StartStore(Protocol):
    async def get(self, code: str) -> Lobby | None: ...
    async def begin_start(self, code: str, actor: str, snapshot: Lobby | None,
                          plan: GameInitialization | None) -> str: ...
    async def finish_start(self, code: str, map_id: str, game_id: str) -> str: ...
    async def abort_start(self, plan: GameInitialization) -> bool: ...
    async def due_starts(self) -> list[str]: ...
    async def claim_start(self, member: str) -> tuple[str, GameInitialization | None]: ...


ConfirmStart = Callable[[str, str, str], Awaitable[str]]


class LobbyStore(Protocol):
    async def get(self, code: str) -> Lobby | None: ...
    async def create(self, code: str, host_id: str, host_name: str) -> bool: ...
    async def add_player(self, code: str, user_id: str, display_name: str) -> str: ...
    async def leave(self, code: str, user_id: str) -> str: ...
    async def set_ready(self, code: str, user_id: str, ready: bool) -> str: ...
    async def add_bot(self, code: str, host_id: str) -> str: ...
    async def remove_bot(self, code: str, host_id: str, bot_id: str) -> str: ...
    async def kick(self, code: str, host_id: str, target_id: str) -> str: ...
    async def vote(self, code: str, user_id: str, map_id: str) -> str: ...
